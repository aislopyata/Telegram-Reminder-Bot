-- Habit tracker: habits, daily completions and per-user daily tracking reminder.
-- Additive and idempotent migration for the existing PostgreSQL database.
-- Apply with:
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f deploy/migrations/20261025_habits.up.sql

BEGIN;

CREATE TABLE IF NOT EXISTS public.habits (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    name text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    CONSTRAINT habits_pkey PRIMARY KEY (id),
    CONSTRAINT habits_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT habits_name_check CHECK (name = btrim(name) AND char_length(name) BETWEEN 1 AND 100)
);

CREATE INDEX IF NOT EXISTS habits_user_active_idx
    ON public.habits USING btree (user_id, is_active, created_at);

CREATE TABLE IF NOT EXISTS public.habit_completions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    habit_id bigint NOT NULL,
    completion_date date NOT NULL,
    completed_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT habit_completions_pkey PRIMARY KEY (id),
    CONSTRAINT habit_completions_habit_id_fkey FOREIGN KEY (habit_id) REFERENCES public.habits(id) ON DELETE CASCADE,
    CONSTRAINT habit_completions_unique UNIQUE (habit_id, completion_date)
);

CREATE INDEX IF NOT EXISTS habit_completions_habit_date_idx
    ON public.habit_completions USING btree (habit_id, completion_date);

CREATE INDEX IF NOT EXISTS habit_completions_date_idx
    ON public.habit_completions USING btree (completion_date);

CREATE TABLE IF NOT EXISTS public.habit_reminder_settings (
    user_id bigint NOT NULL,
    reminder_time time without time zone,
    is_enabled boolean DEFAULT false NOT NULL,
    last_notified_date date,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT habit_reminder_settings_pkey PRIMARY KEY (user_id),
    CONSTRAINT habit_reminder_settings_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT habit_reminder_settings_time_check CHECK (is_enabled = false OR reminder_time IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS habit_reminder_settings_enabled_idx
    ON public.habit_reminder_settings USING btree (user_id) WHERE is_enabled;

DROP TRIGGER IF EXISTS habit_reminder_settings_set_updated_at ON public.habit_reminder_settings;
CREATE TRIGGER habit_reminder_settings_set_updated_at
    BEFORE UPDATE ON public.habit_reminder_settings
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMIT;
