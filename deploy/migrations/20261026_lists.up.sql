-- ToDo lists, wish lists and persistent primary-UI message state.
-- Additive and idempotent: safe to run on an existing production database.

CREATE TABLE IF NOT EXISTS public.todo_lists (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name text NOT NULL,
    is_default boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT todo_lists_pkey PRIMARY KEY (id),
    CONSTRAINT todo_lists_name_check CHECK (
      (name = btrim(name)) AND (char_length(name) >= 1) AND (char_length(name) <= 100)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS todo_lists_owner_default_idx
    ON public.todo_lists (owner_user_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS todo_lists_owner_idx
    ON public.todo_lists (owner_user_id, is_default DESC, created_at);

CREATE TABLE IF NOT EXISTS public.todo_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    list_id bigint NOT NULL REFERENCES public.todo_lists(id) ON DELETE CASCADE,
    title text NOT NULL,
    description text,
    url text,
    is_completed boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT todo_items_pkey PRIMARY KEY (id),
    CONSTRAINT todo_items_title_check CHECK (
      (title = btrim(title)) AND (char_length(title) >= 1) AND (char_length(title) <= 200)
    ),
    CONSTRAINT todo_items_description_check CHECK (
      description IS NULL OR char_length(description) <= 2000
    ),
    CONSTRAINT todo_items_url_check CHECK (url IS NULL OR char_length(url) <= 500)
);

CREATE INDEX IF NOT EXISTS todo_items_list_idx
    ON public.todo_items (list_id, created_at);

CREATE TABLE IF NOT EXISTS public.todo_list_shares (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    list_id bigint NOT NULL REFERENCES public.todo_lists(id) ON DELETE CASCADE,
    shared_with_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    permission text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT todo_list_shares_pkey PRIMARY KEY (id),
    CONSTRAINT todo_list_shares_permission_check CHECK (permission IN ('READ', 'EDIT')),
    CONSTRAINT todo_list_shares_unique UNIQUE (list_id, shared_with_user_id)
);

CREATE INDEX IF NOT EXISTS todo_list_shares_user_idx
    ON public.todo_list_shares (shared_with_user_id);

CREATE TABLE IF NOT EXISTS public.wish_lists (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name text NOT NULL,
    is_default boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT wish_lists_pkey PRIMARY KEY (id),
    CONSTRAINT wish_lists_name_check CHECK (
      (name = btrim(name)) AND (char_length(name) >= 1) AND (char_length(name) <= 100)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS wish_lists_owner_default_idx
    ON public.wish_lists (owner_user_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS wish_lists_owner_idx
    ON public.wish_lists (owner_user_id, is_default DESC, created_at);

CREATE TABLE IF NOT EXISTS public.wish_list_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    list_id bigint NOT NULL REFERENCES public.wish_lists(id) ON DELETE CASCADE,
    title text NOT NULL,
    description text,
    url text,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT wish_list_items_pkey PRIMARY KEY (id),
    CONSTRAINT wish_list_items_title_check CHECK (
      (title = btrim(title)) AND (char_length(title) >= 1) AND (char_length(title) <= 200)
    ),
    CONSTRAINT wish_list_items_description_check CHECK (
      description IS NULL OR char_length(description) <= 2000
    ),
    CONSTRAINT wish_list_items_url_check CHECK (url IS NULL OR char_length(url) <= 500)
);

CREATE INDEX IF NOT EXISTS wish_list_items_list_idx
    ON public.wish_list_items (list_id, created_at);

CREATE TABLE IF NOT EXISTS public.wish_list_shares (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    list_id bigint NOT NULL REFERENCES public.wish_lists(id) ON DELETE CASCADE,
    shared_with_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT wish_list_shares_pkey PRIMARY KEY (id),
    CONSTRAINT wish_list_shares_unique UNIQUE (list_id, shared_with_user_id)
);

CREATE INDEX IF NOT EXISTS wish_list_shares_user_idx
    ON public.wish_list_shares (shared_with_user_id);

-- One primary bot message per user/chat. The message id may become stale; the
-- UI layer detects that and sends a replacement, then updates this row.
CREATE TABLE IF NOT EXISTS public.ui_state (
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    chat_id bigint NOT NULL,
    message_id bigint,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ui_state_pkey PRIMARY KEY (user_id, chat_id)
);

CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'todo_lists_set_updated_at'
  ) THEN
    CREATE TRIGGER todo_lists_set_updated_at BEFORE UPDATE ON public.todo_lists
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'todo_items_set_updated_at'
  ) THEN
    CREATE TRIGGER todo_items_set_updated_at BEFORE UPDATE ON public.todo_items
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'wish_lists_set_updated_at'
  ) THEN
    CREATE TRIGGER wish_lists_set_updated_at BEFORE UPDATE ON public.wish_lists
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgname = 'wish_list_items_set_updated_at'
  ) THEN
    CREATE TRIGGER wish_list_items_set_updated_at BEFORE UPDATE ON public.wish_list_items
      FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
  END IF;
END;
$$;
